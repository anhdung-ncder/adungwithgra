#!/usr/bin/env node
/**
 * Zero-dependency bundler for Antigravity Custom Theme Injector.
 * - Embeds all wallpaper images in assets/wallpapers/ as base64 Data URIs
 * - Concatenates src/ modules in dependency order into a single standalone IIFE:
 *   dist/antigravity-theme-injector.js
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, '..');
const srcDir = path.join(rootDir, 'src');
const wallpapersDir = path.join(rootDir, 'assets', 'wallpapers');
const outFile = path.join(rootDir, 'dist', 'antigravity-theme-injector.js');

const MODULE_ORDER = [
  'assets/mascots.js',
  'assets/stickers.js',
  'assets/wallpapers-manifest.js',
  'presets/bubbles.js',
  'presets/inputs.js',
  'presets/atmosphere.js',
  'presets/themes.js',
  'core/storage.js',
  'core/styles.js',
  'core/ambient-canvas.js',
  'core/dom-adapter.js',
  'ui/pet-stage.js',
  'ui/sticker-layer.js',
  'ui/settings-panel.js',
  'index.js'
];

function encodeWallpaper(filename) {
  const fullPath = path.join(wallpapersDir, filename);
  if (!fs.existsSync(fullPath)) return '';
  const ext = path.extname(filename).toLowerCase();
  const mime = ext === '.png' ? 'image/png' : ext === '.webp' ? 'image/webp' : 'image/jpeg';
  const b64 = fs.readFileSync(fullPath).toString('base64');
  return `data:${mime};base64,${b64}`;
}

function stripModuleSyntax(code) {
  return code
    .replace(/^\s*import\s+[\s\S]*?from\s+['"][^'"]+['"];\s*$/gm, '')
    .replace(/^\s*export\s+(?=(?:const|let|var|function|async\s+function|class)\b)/gm, '')
    .trim();
}

const embeddedMap = {
  'minato-hokage-8k': encodeWallpaper('minato-hokage-8k.jpg'),
  'thunder-samurai': encodeWallpaper('thunder-samurai.jpg'),
  'cosmic-violin-4k': encodeWallpaper('cosmic-violin-4k.jpg'),
  'cosmic-earth-night': encodeWallpaper('cosmic-earth-night.jpg'),
  'sakura-shrine-night': encodeWallpaper('sakura-shrine-night.jpg'),
  'jade-dragon-mist': encodeWallpaper('jade-dragon-mist.jpg')
};

const parts = [
  `/**`,
  ` * Antigravity Custom Theme Injector (Standalone Single-File Bundle)`,
  ` * Generated by scripts/build.mjs — zero external dependencies, non-destructive runtime overlay.`,
  ` * Public API: window.__AGY_CUSTOM_THEME__ (.openSettings(), .applyBundle(id), .destroy())`,
  ` */`,
  `(function () {`,
  `  'use strict';`
];

for (const rel of MODULE_ORDER) {
  const full = path.join(srcDir, rel);
  let code = fs.readFileSync(full, 'utf8');

  if (rel === 'assets/wallpapers-manifest.js') {
    for (const [id, dataUri] of Object.entries(embeddedMap)) {
      if (!dataUri) continue;
      const pattern = new RegExp(`(id:\\s*'${id}'[\\s\\S]*?embeddedDataUri:\\s*)''`);
      code = code.replace(pattern, `$1'${dataUri}'`);
    }
  }

  parts.push(`\n  // ===== ${rel} =====`);
  parts.push(stripModuleSyntax(code));
}

parts.push(`\n})();\n`);

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, parts.join('\n'), 'utf8');

const sizeKb = (fs.statSync(outFile).size / 1024).toFixed(1);
console.log(`Built ${outFile} (${sizeKb} KB)`);
